import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright-core';
import {WebSocket} from 'ws';
import {createApp} from '../../src/server/app.js';
import {readConfig} from '../../src/server/config.js';

test('real Chromium: local DOM, remote input, streaming, resources, navigation and isolation',{timeout:120000},async t=>{
  const config=readConfig({...process.env,PORT:'0',ENGINE_MODE:'demo',ENGINE_HOST:'127.0.0.1'});
  const app=await createApp(config);
  const browser=await chromium.launch({executablePath:config.chromiumPath,headless:true,chromiumSandbox:true});
  t.after(async()=>{await browser.close();await app.close();});
  const context=await browser.newContext({viewport:{width:1440,height:1080}});
  const page=await context.newPage();const requests:string[]=[];const errors:string[]=[];
  page.on('request',request=>requests.push(request.url()));page.on('pageerror',error=>errors.push(error.message));
  await page.goto(app.origin);await page.getByRole('button',{name:'打开体验页面'}).click();
  const mirror=page.frameLocator('#mirror');
  await mirror.getByRole('heading',{name:'这段页面，在你的浏览器渲染。'}).waitFor({timeout:30000});
  await mirror.getByRole('button',{name:'远端计数 +1'}).click();
  await mirror.getByText('1',{exact:true}).waitFor();
  const textarea=mirror.getByPlaceholder('在这里输入中文');await textarea.fill('你好，远端引擎');
  await mirror.getByText('远端收到：你好，远端引擎',{exact:true}).waitFor();
  await mirror.getByRole('button',{name:'生成流式回答'}).click();
  await mirror.getByText('远端回答：你好，远端引擎。这段文字通过 DOM 增量更新传到了本地。',{exact:true}).waitFor();
  await mirror.getByRole('button',{name:'通过 CSSOM 修改主题'}).click();
  const styled=mirror.getByText('我的颜色由远端 CSSOM 决定。',{exact:true});
  await page.waitForFunction(()=>document.getElementById('revision')!.textContent!=='0');
  await styled.evaluate(async element=>{for(let i=0;i<50;i++){if(getComputedStyle(element).color==='rgb(196, 67, 35)')return;await new Promise(r=>setTimeout(r,100));}throw new Error('CSSOM change was not mirrored');});
  const image=mirror.getByAltText('经授权资源通道传输的测试图片');
  assert.ok((await image.getAttribute('src'))?.startsWith('blob:'));
  await image.evaluate(async node=>{const image=node as HTMLImageElement;await image.decode();});
  const inner=page.frames().find(frame=>frame.url().endsWith('/mirror'))!;
  assert.equal(await inner.evaluate(()=>typeof (window as unknown as Record<string,unknown>).__REMOTE_ONLY_MARKER),'undefined');
  assert.equal(await page.evaluate(()=>localStorage.getItem('remote-demo')),null);
  assert.equal(requests.some(url=>url.startsWith(app.fixtureOrigin)),false,'local browser must not access target origin');
  assert.equal(await mirror.locator('script:not([nonce]), iframe, [onclick], input[type=hidden]').count(),0);
  await inner.evaluate(()=>window.scrollTo(0,0));
  await new Promise(resolve=>setTimeout(resolve,400));
  await mkdir('artifacts',{recursive:true});await page.screenshot({path:'artifacts/workbench.png',fullPage:true});
  const state=await page.evaluate(async()=>await(await fetch('/api/state')).json());
  const sessionId=state.sessions[0].id as string;
  const session=app.sessions.get(sessionId)!;
  assert.equal(await session.page.evaluate(()=>typeof(window as unknown as Record<string,unknown>).__REMOTE_ONLY_MARKER),'string');
  assert.equal((await session.context.cookies()).some(cookie=>cookie.name==='remote-session'),true);
  await t.test('second visitor cannot read, control or fetch another session',async()=>{
    const other=await browser.newContext();const otherPage=await other.newPage();await otherPage.goto(app.origin);
    await otherPage.waitForFunction(()=>document.getElementById('mode')!.textContent==='受控测试模式');
    const assetId=[...session.assets.keys()][0];assert.ok(assetId);
    const statuses=await otherPage.evaluate(async ({id,assetId})=>{
      const read=await fetch('/api/sessions/'+id);
      const navigate=await fetch('/api/sessions/'+id+'/navigate',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({url:'http://127.0.0.1'})});
      const asset=await fetch('/api/sessions/'+id+'/assets/'+assetId);
      return [read.status,navigate.status,asset.status];
    },{id:sessionId,assetId});assert.deepEqual(statuses,[404,404,404]);
    const cookie=(await other.cookies()).map(c=>`${c.name}=${c.value}`).join('; ');
    await new Promise<void>((resolve,reject)=>{const ws=new WebSocket(app.origin.replace('http:','ws:')+`/api/sessions/${sessionId}/stream`,{origin:app.origin,headers:{Cookie:cookie}});ws.on('open',()=>{ws.close();reject(new Error('Cross-owner WebSocket accepted'));});ws.on('unexpected-response',(_req,res)=>{assert.equal(res.statusCode,403);res.resume();ws.terminate();resolve();});ws.on('error',()=>{});});
    const own=await otherPage.evaluate(async()=>await(await fetch('/api/sessions',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'})).json());
    assert.ok(own.id,'second visitor can create an independent session');
    const second=app.sessions.get(own.id)!;
    const firstCookie=(await session.context.cookies()).find(c=>c.name==='remote-session')?.value;
    const secondCookie=(await second.context.cookies()).find(c=>c.name==='remote-session')?.value;
    assert.ok(firstCookie&&secondCookie);assert.notEqual(firstCookie,secondCookie);
    await session.page.evaluate(()=>localStorage.setItem('private-test','owner-one'));
    assert.equal(await second.page.evaluate(()=>localStorage.getItem('private-test')),null);
    await otherPage.evaluate(async id=>await fetch('/api/sessions/'+id,{method:'DELETE'}),own.id);
    await other.close();
  });
  await t.test('wrong origin, stale document events and invalid input are rejected',async()=>{
    const cookies=(await context.cookies()).map(c=>`${c.name}=${c.value}`).join('; ');
    const response=await fetch(app.origin+'/api/sessions/'+sessionId+'/navigate',{method:'POST',headers:{Cookie:cookies,Origin:'https://untrusted.test','Content-Type':'application/json'},body:JSON.stringify({url:app.fixtureOrigin})});
    assert.equal(response.status,403);
    await new Promise<void>((resolve,reject)=>{
      const ws=new WebSocket(app.origin.replace('http:','ws:')+`/api/sessions/${sessionId}/stream`,{origin:app.origin,headers:{Cookie:cookies}});
      const timer=setTimeout(()=>{ws.close();reject(new Error('No stale event rejection'));},5000);
      ws.on('message',data=>{const message=JSON.parse(data.toString());if(message.type==='snapshot')ws.send(JSON.stringify({type:'event',epoch:'old-document',eventId:999,action:'click',nodeId:'n1'}));if(message.type==='error'){assert.equal(message.eventId,999);clearTimeout(timer);ws.close();resolve();}});
      ws.on('error',reject);
    });
  });
  await t.test('reconnect provides a full snapshot without rerunning target scripts',async()=>{
    for(const socket of session.sockets)socket.close(1012,'test reconnect');
    await page.getByText('已断开',{exact:true}).waitFor();
    await page.getByText('在线',{exact:true}).waitFor();
    await mirror.getByText('1',{exact:true}).waitFor();
    assert.equal(await session.page.locator('#count').textContent(),'1');
  });
  await mirror.getByRole('link').click();
  await mirror.getByRole('heading',{name:'导航成功'}).waitFor();
  assert.ok((await mirror.locator('p').textContent())?.includes('remote-session='));
  await page.getByRole('button',{name:'后退',exact:true}).click();
  await mirror.getByRole('heading',{name:'这段页面，在你的浏览器渲染。'}).waitFor();
  await t.test('dangerous target markup is not executable in the local frame',async()=>{
    await page.getByRole('textbox',{name:'目标网址'}).fill(app.fixtureOrigin+'/attack');await page.getByRole('button',{name:'前往',exact:true}).click();
    await mirror.getByRole('heading',{name:'攻击性内容测试'}).waitFor();
    assert.equal(await inner.evaluate(()=>typeof(window as unknown as Record<string,unknown>).attackerRan),'undefined');
    const content=JSON.stringify(session.current);
    assert.equal(content.includes('hidden-secret'),false);assert.equal(content.includes('password-secret'),false);
    assert.equal(await mirror.locator('[onclick], [onerror], [onload], iframe, foreignObject, use, input[type=hidden]').count(),0);
    assert.equal(await mirror.locator('a').getAttribute('href'),null);
  });
  await page.getByRole('button',{name:'关闭会话',exact:true}).click();
  await page.getByText('会话已销毁，远端浏览器已关闭',{exact:true}).waitFor();
  assert.equal(app.sessions.size,0);
  assert.deepEqual(errors,[]);
});
